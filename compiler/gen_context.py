"""Generate the appendices of docs/kgc-kronos-context.md, the file Boss gives other Claude chats (D54).

The file is a hand-written core (sections 1 to 12) above MARKER and generated appendices below
it: the language reference, the rest of the Orchestrator prompt, every spec with the VBA the
compiler writes for it, DECISIONS.md, the semantics tables, ForgeLib, CLAUDE.md and the plans.
Copies made by this script can't go stale: a unit test fails when the file differs from what it
builds, and when it passes Boss's 3 MB cap.

Usage: python compiler/gen_context.py [--check]   (--check fails if the file is out of date)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "compiler"))
from vcl_codegen import compile_text  # noqa: E402

CONTEXT = ROOT / "docs" / "kgc-kronos-context.md"
MARKER = "<!-- Everything below is generated by python compiler/gen_context.py from the repo: do not edit by hand. -->"
LIMIT = 3_000_000   # Boss's cap, in bytes; a 200,000-token chat reads about 800 KB, so stay far below
RULES = ("1.  Reply with exactly", "removes or replaces a sheet.")
REFERENCE = ("TASK FORMAT", "the same spec always builds the same file.")
PLANS = ["CLAUDE.md", "docs/vcl-mvp-plan.md", "docs/ai-plan.md", "docs/excel-pilot.md"]
DESIGNS = "docs/vep-*.md"   # every language design, newest first
FINDINGS = ["docs/vcl-m2-findings.md"]


def read(path):
    return (ROOT / path).read_text(encoding="utf-8")


def between(text, start, end):
    """The text from start to end, both included (exactly one match, as the shared-text tests ask)."""
    i = text.index(start)
    return text[i:text.index(end, i) + len(end)]


def fenced(text, lang="text"):
    """A code block that can hold text with ``` lines in it."""
    fence = "````" if "```" in text else "```"
    return f"{fence}{lang}\n{text.rstrip()}\n{fence}"


def shifted(markdown, by=2):
    """Markdown with its headings moved down `by` levels (at most ######), code blocks untouched."""
    out, fence = [], None
    for line in markdown.rstrip().split("\n"):
        mark = re.match(r"^(`{3,}|~{3,})", line)
        if mark and (fence is None or mark.group(1).startswith(fence)):
            fence = None if fence else mark.group(1)
        elif fence is None and re.match(r"^#{1,6} ", line):
            hashes = len(line) - len(line.lstrip("#"))
            line = "#" * min(6, hashes + by) + line[hashes:]
        out.append(line)
    return "\n".join(out)


def appendices():
    spec, prompt = read("vcl/spec.md"), read("vcl/orchestrator_prompt.txt")
    version = re.match(r"# (VCL \d+\.\d+)", spec).group(1)
    parts = [MARKER, "", f"## Appendix A: the full {version} reference", "",
             "Copied word for word from `vcl/spec.md`, the same text the Orchestrator prompt contains. A unit",
             "test fails if this copy ever differs from spec.md. The parts of spec.md not copied here are the",
             "exact fixture algorithm and the changelogs.", "",
             "### Hard rules", "", fenced(between(spec, *RULES)), "",
             "### Reference", "", fenced(between(spec, *REFERENCE)), "",
             "## Appendix B: the rest of the Orchestrator prompt", "",
             "The parts of `vcl/orchestrator_prompt.txt` that are not in Appendix A: its role, its examples",
             "and the final check it runs before every reply.", "",
             fenced(prompt[:prompt.index("HARD RULES")]), "",
             fenced(prompt[prompt.index(REFERENCE[1]) + len(REFERENCE[1]):].strip()), "",
             "## Appendix C: the specs, each with the VBA the compiler writes for it", "",
             "Every spec in `specs/`, then the procedure `vcl_codegen.py` makes from it. In Excel each",
             "procedure calls ForgeLib (Appendix F); `dist/forge_module.bas` is ForgeLib plus these.", ""]
    for path in sorted((ROOT / "specs").glob("*.vcl")):
        text = path.read_text(encoding="utf-8")
        proc = re.search(r"^PROC\s+(\w+)", text, re.M).group(1)
        parts += [f"### {path.name}: {proc}", "", fenced(text, "vcl"), "",
                  fenced(compile_text(text, path.name), "vba"), ""]
    parts += ["## Appendix D: DECISIONS.md, in full", "", shifted(read("DECISIONS.md")), "",
              "## Appendix E: the meaning of the value functions (`docs/vcl-semantics.md`)", "",
              shifted(read("docs/vcl-semantics.md")), "",
              "## Appendix F: ForgeLib, the VBA runtime (`vba/ForgeLib.bas`)", "",
              fenced(read("vba/ForgeLib.bas"), "vba"), "",
              "## Appendix G: the brief, the plans and the language designs", "",
              "CLAUDE.md (the brief Claude Code reads first), the plans, then every VEP, newest first.", ""]
    designs = sorted((str(p.relative_to(ROOT)) for p in ROOT.glob(DESIGNS)), reverse=True)
    for path in PLANS + designs + FINDINGS:
        parts += [f"### `{path}`", "", shifted(read(path), by=3), ""]
    return "\n".join(parts).rstrip() + "\n"


def build():
    """The whole file: the hand-written core as it stands, then fresh appendices."""
    current = CONTEXT.read_text(encoding="utf-8")
    core = current.split(MARKER)[0] if MARKER in current else current.split("## Appendix A:")[0]
    return core.rstrip() + "\n\n" + appendices()


def main(argv):
    text = build()
    size = len(text.encode("utf-8"))
    if size > LIMIT:
        print(f"{CONTEXT.relative_to(ROOT)} would be {size:,} bytes, over the {LIMIT:,} limit")
        return 1
    if "--check" in argv:
        if CONTEXT.read_text(encoding="utf-8") != text:
            print(f"{CONTEXT.relative_to(ROOT)} is out of date: run python compiler/gen_context.py")
            return 1
        print(f"{CONTEXT.relative_to(ROOT)} is up to date ({size:,} bytes)")
        return 0
    CONTEXT.write_text(text, encoding="utf-8")
    print(f"wrote {CONTEXT.relative_to(ROOT)} ({size:,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
