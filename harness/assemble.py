"""Assemble the paste-ready pilot batch and its expected results.

Usage:  python harness/assemble.py           rebuild batches/batch_000_pilot.bas and .expected.csv
        python harness/assemble.py --check   exit 1 if the committed files are out of date

The batch is ONE module: the harness/ForgeTest.bas engine, the batch's test list, the fixture
builders generated by harness/fixtures.py, and the pilot code (harness/pilot/task_01.bas).
Before writing, it checks that the module is safe to paste into a blank Excel 2016 workbook
(see paste_problems) and refuses to write it otherwise.
"""
import csv
import importlib.util
import io
import os
import re
import sys
from collections import Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path[:0] = [os.path.join(ROOT, "compiler"), os.path.join(ROOT, "harness")]

from fixtures import build_file, vba_for_file  # noqa: E402
from parser import parse_spec  # noqa: E402

BATCH = {
    "name": "000_pilot",
    "spec": "specs/task_01.vcl",
    "fixture": "bom_grn_01.xlsx",
    "code": "harness/pilot/task_01.bas",
    "expected": "harness/pilot/task_01_expected.py",
    "bas": "batches/batch_000_pilot.bas",
    "csv": "batches/batch_000_pilot.expected.csv",
}
ENGINE = "harness/ForgeTest.bas"
MAX_LINE = 1023
MAX_CONTINUATIONS = 24
FORBIDDEN = [  # (pattern on code without strings and comments, why)
    (r"\.(Select|Activate)\b", "no Select or Activate"),
    (r"^\s*Attribute\b", "no Attribute lines: they break a pasted module"),
    (r"\bOption\s+Private\b", "Option Private hides RunBatch from Alt+F8"),
    (r"\b(Kill|RmDir|Shell|Declare)\b", "no Kill, RmDir, Shell or API Declare"),
    (r"\.SaveAs\b", "no SaveAs in a batch"),
]


def read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return f.read()


def load_module(path, name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(ROOT, path))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def build():
    """Returns (bas text, csv text) for the batch."""
    spec = parse_spec(read(BATCH["spec"]))
    sheets = build_file(spec.fixtures, BATCH["fixture"])
    code = read(BATCH["code"]).rstrip("\n")
    tests = re.findall(r"^Private Sub (ForgeTest_\w+)\(\)", code, re.M)
    engine = read(ENGINE).rstrip("\n").split("\n")
    banner = [
        "' " + "=" * 93,
        f"' VBA Forge batch {BATCH['name']}: generated by harness/assemble.py from {BATCH['spec']}. Do not edit.",
        "' Paste this whole file into ONE new module of a blank workbook (Alt+F11, Insert > Module),",
        "' then press Alt+F8 and run RunBatch. Guide: harness/PILOT.md",
        "' " + "=" * 93,
    ]
    batch = [
        "' " + "=" * 93,
        f"' Batch {BATCH['name']}: the test list",
        "' " + "=" * 93,
        "Private Function ForgeBatchName() As String",
        f'    ForgeBatchName = "{BATCH["name"]}"',
        "End Function",
        "",
        "Private Function ForgeBatchTestCount() As Long",
        f"    ForgeBatchTestCount = {len(tests)}",
        "End Function",
        "",
        "Private Sub ForgeBatchTests()",
        *[f"    {name}" for name in tests],
        "End Sub",
    ]
    parts = [engine[0], "", *banner, *engine[1:], "", *batch, "", vba_for_file(BATCH["fixture"], sheets), code]
    bas = "\n".join(parts) + "\n"

    expected = load_module(BATCH["expected"], "pilot_expected")
    rows, info = expected.expected_tests(sheets)
    out = io.StringIO()
    writer = csv.writer(out, lineterminator="\n")
    writer.writerow(["test_id", "spec", "spec_line", "expected_outcome", "measure", "expected_value",
                     "shown_in_results"])
    for test in rows:
        for measure, value in test["measures"].items():
            writer.writerow([test["id"], test["spec"], test["line"], test["outcome"], measure, number(value), "yes"])
    first = rows[0]
    for label, key in (("Shortages rows: Not received", "not_received"), ("Shortages rows: Short", "short"),
                       ("Shortages rows: Required qty missing", "missing")):
        writer.writerow([first["id"], first["spec"], first["line"], first["outcome"], label, info[key], "no"])
    return bas, out.getvalue()


def number(value):
    if isinstance(value, float) and value.is_integer():
        return int(value)
    return value


# ---------------------------------------------------------------- paste safety checks

def logical_lines(text):
    """Physical lines joined across ' _' continuations: [(first line number, text, continuations)]."""
    out, buf, start, count = [], [], 0, 0
    for n, line in enumerate(text.split("\n"), 1):
        if not buf:
            start, count = n, 0
        if line.endswith(" _"):
            buf.append(line[:-2])
            count += 1
            continue
        buf.append(line)
        out.append((start, " ".join(buf), count))
        buf = []
    return out


def strip_code(line):
    """The code part of a line: strings emptied, comment removed."""
    code = re.sub(r'"(?:[^"]|"")*"', '""', line)
    return code.split("'", 1)[0]


def paste_problems(text):
    problems = []
    physical = text.split("\n")
    if physical[0] != "Option Explicit":
        problems.append("line 1: the module must start with Option Explicit")
    for n, line in enumerate(physical, 1):
        if not line.isascii():
            problems.append(f"line {n}: non-ASCII character (the VBA editor would garble it)")
        if len(line) > MAX_LINE:
            problems.append(f"line {n}: {len(line)} characters (VBA allows {MAX_LINE})")
        if line.rstrip().endswith("_") and not line.endswith(" _") and not line.lstrip().startswith("'"):
            problems.append(f"line {n}: a line continuation needs ' _' at the very end")
    lines = logical_lines(text)
    for n, line, count in lines:
        if count > MAX_CONTINUATIONS:
            problems.append(f"line {n}: {count} line continuations (VBA allows {MAX_CONTINUATIONS})")
        code = strip_code(line)
        for pattern, why in FORBIDDEN:
            if re.search(pattern, code):
                problems.append(f"line {n}: {why}")
        for created in re.findall(r"\bCreateObject\(([^)]*)\)", line.split("'", 1)[0]):
            if created.strip() != '"Scripting.Dictionary"':
                problems.append(f"line {n}: only CreateObject(\"Scripting.Dictionary\") is allowed")
    problems += procedure_problems(lines)
    return problems


PROC_START = re.compile(r"^(?:(?:Public|Private)\s+)?(Sub|Function)\s+(\w+)\s*\((.*)\)\s*(?:As\s+[\w.]+)?\s*$")
PROC_END = re.compile(r"^End\s+(Sub|Function)\s*$")


def procedure_problems(lines):
    """Undeclared variables (Option Explicit), unknown Forge* calls, labels and line numbers."""
    problems = []
    module_names, procs, current = set(), [], None
    for n, line, _ in lines:
        code = strip_code(line).strip()
        if current is None:
            m = PROC_START.match(code)
            if m:
                current = {"kind": m.group(1), "name": m.group(2), "line": n, "params": m.group(3), "body": []}
            elif re.match(r"^(Private|Public|Dim)\s+(Const\s+)?\w+", code):
                module_names.add(re.match(r"^(?:Private|Public|Dim)\s+(?:Const\s+)?(\w+)", code).group(1))
            elif PROC_END.match(code):
                problems.append(f"line {n}: End {PROC_END.match(code).group(1)} without a procedure")
        else:
            if PROC_END.match(code):
                if PROC_END.match(code).group(1) != current["kind"]:
                    problems.append(f"line {n}: {current['name']} ends with the wrong End statement")
                procs.append(current)
                current = None
            elif PROC_START.match(code):
                problems.append(f"line {n}: a procedure starts inside {current['name']}")
            else:
                current["body"].append((n, code))
    if current is not None:
        problems.append(f"line {current['line']}: {current['name']} has no End {current['kind']}")
    names = Counter(p["name"] for p in procs)
    for name, count in names.items():
        if count > 1:
            problems.append(f"procedure {name} is defined {count} times")
    defined = set(names) | module_names
    for proc in procs:
        declared = set(module_names) | {proc["name"]}
        for param in filter(None, (p.strip() for p in proc["params"].split(","))):
            m = re.match(r"(?:Optional\s+)?(?:ByVal\s+|ByRef\s+)?(?:ParamArray\s+)?(\w+)", param)
            declared.add(m.group(1))
        labels, used_labels, numbers = set(), set(), Counter()
        for n, code in proc["body"]:
            m = re.match(r"^\s*Dim\s+(.*)$", code)
            if m:
                declared |= {re.match(r"\s*(\w+)", part).group(1) for part in m.group(1).split(",")}
            m = re.match(r"^([A-Za-z]\w*):\s*$", code)
            if m:
                labels.add(m.group(1))
            m = re.match(r"^(\d+)\s", code)
            if m:
                numbers[m.group(1)] += 1
            for label in re.findall(r"\b(?:GoTo|Resume)\s+([A-Za-z]\w*)", code):
                if label != "Next":
                    used_labels.add(label)
        for label in used_labels - labels:
            problems.append(f"{proc['name']}: GoTo/Resume to missing label {label}")
        for number_text, count in numbers.items():
            if count > 1:
                problems.append(f"{proc['name']}: line number {number_text} is used {count} times")
        for n, code in proc["body"]:
            if re.match(r"^\s*Dim\s", code):
                continue
            body = re.sub(r"^\d+\s+", "", code)
            body = re.sub(r"\w+:=", "", body)            # named arguments
            body = re.sub(r"\.\s*\w+", "", body)         # members: .Value, .Cells, ...
            body = re.sub(r"^\s*[A-Za-z]\w*:\s*$", "", body)  # labels
            for word in re.findall(r"\b([a-z]\w*)\b", body):
                if word.startswith(("vb", "xl")) or word in declared:
                    continue
                problems.append(f"line {n}: {word} is not declared in {proc['name']} (Option Explicit)")
            for word in re.findall(r"\b(Forge\w+)\b", body):
                if word not in defined:
                    problems.append(f"line {n}: {word} is not defined in the module")
    return problems


def main(argv):
    bas, expected = build()
    problems = paste_problems(bas)
    if problems:
        for p in problems:
            print(f"{BATCH['bas']}: {p}")
        return 1
    targets = {BATCH["bas"]: bas, BATCH["csv"]: expected}
    if "--check" in argv:
        stale = []
        for path, content in targets.items():
            try:
                current = read(path)
            except OSError:
                current = None
            if current != content:
                stale.append(path)
        for path in stale:
            print(f"{path} is out of date: run python harness/assemble.py and commit the result")
        if not stale:
            print("batch files are up to date")
        return 1 if stale else 0
    for path, content in targets.items():
        with open(os.path.join(ROOT, path), "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
